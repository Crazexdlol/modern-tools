// One-off: parse the agent-produced FAQ files (markdown + text) and the
// existing loss-of-use TS source → emit a unified src/lib/faq-content.ts.
// Run once after a research batch. Safe to re-run (overwrites the output).

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(here, '..')
const repoRoot = resolve(projectRoot, '..')

function parseQAs(path, topicId) {
  const text = readFileSync(path, 'utf-8')
  const qas = []
  const lines = text.split(/\r?\n/)
  let currentQ = null
  let currentA = []
  let count = 0

  const flush = () => {
    if (currentQ) {
      const answer = currentA.join(' ').trim().replace(/\s+/g, ' ')
      if (answer) {
        count++
        qas.push({
          id: `${topicId}-${String(count).padStart(3, '0')}`,
          topic: topicId,
          question: currentQ.trim(),
          answer,
        })
      }
    }
    currentQ = null
    currentA = []
  }

  for (const raw of lines) {
    const line = raw.replace(/^\s*\d+\.\s*/, '').trim()
    // Match Q: ..., Q1: ..., Q12: ..., with optional surrounding **
    const qMatch = line.match(/^\*{0,2}Q\d*:\s*(.+?)\*{0,2}\s*$/i)
    const aMatch = line.match(/^\*{0,2}A\d*:\s*(.+)$/i)
    if (qMatch) {
      flush()
      currentQ = qMatch[1].replace(/\*+/g, '').trim()
    } else if (aMatch && currentQ) {
      currentA.push(aMatch[1].replace(/\*+/g, '').trim())
    } else if (currentQ && currentA.length > 0 && line.length > 0) {
      currentA.push(line.replace(/\*+/g, '').trim())
    }
  }
  flush()
  return qas
}

const acv  = parseQAs(resolve(projectRoot, 'docs/faq-source/acv-faq.md'),              'acv')
const dv   = parseQAs(resolve(projectRoot, 'docs/faq-source/DV_FAQ.md'),               'dv')
const cor  = parseQAs(resolve(projectRoot, 'docs/faq-source/faq-cost-of-repair-disputes.txt'), 'cost-of-repair')
const stor = parseQAs(resolve(projectRoot, 'docs/faq-source/STORAGE_CHARGES_FAQ.md'),  'storage')

// LOU comes from an already-structured TS file — extract via regex.
const louSrc = readFileSync(resolve(projectRoot, 'src/lib/loss-of-use-faqs.ts'), 'utf-8')
const louMatches = Array.from(louSrc.matchAll(/question:\s*(['"`])([\s\S]*?)\1\s*,\s*answer:\s*(['"`])([\s\S]*?)\3\s*,/g))
const lou = louMatches.map((m, i) => ({
  id: `loss-of-use-${String(i + 1).padStart(3, '0')}`,
  topic: 'loss-of-use',
  question: m[2].trim(),
  answer: m[4].trim().replace(/\s+/g, ' '),
}))

